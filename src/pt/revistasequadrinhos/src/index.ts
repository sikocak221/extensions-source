async function load(url: string) {
  const response = await http.get(url, { headers });
  return { document: html.load(response.body, { baseUrl: response.url }), url: response.url };
}

function parseList(document: HtmlElement): MangaPage {
  const items = document.select('ul.videos > li').map((element): MangaSummary => {
    const a = element.selectFirst('a.titulo');
    if (!a) throw new Error('Manga URL is mandatory');
    return {
      title: a.text().trim(),
      url: relativeUrl(a.attr('href') ?? ''),
      thumbnailUrl: element.selectFirst('div.thumb-conteudo img')?.absUrl('src') || undefined,
    };
  });
  return { items, hasNextPage: document.selectFirst('.paginacao li.next') !== null };
}

const pageSuffix = (page: number) => (page > 1 ? `/page/${page}` : '');

async function list(path: string, page: number, query = ''): Promise<MangaPage> {
  const url = `${BASE_URL}${path}${pageSuffix(page)}${query ? `?s=${encodeURIComponent(query)}` : ''}`;
  return parseList((await load(url)).document);
}

const select = (id: string, label: string, options: [string, string][]): Filter => ({
  type: 'select',
  id,
  label,
  default: '',
  options: options.map(([l, value]) => ({ label: l, value })),
});

export default defineExtension({
  createSource: () => ({
    baseUrl: BASE_URL,
    getPopular: (page) => list('/category/popular-comics', page),
    getLatest: (page) => list('', page),
    getFilters: (): Filter[] => [
      { type: 'header', label: 'Nota: Ignorado se usar pesquisa de texto.' },
      { type: 'separator' },
      select('category', 'Categorias', CATEGORIES),
      { type: 'separator' },
      { type: 'header', label: 'Nota: Ignorado se escolher uma categoria.' },
      select('tag', 'Tags', TAGS),
    ],
    search(query: string, page: number, filters: FilterState): Promise<MangaPage> {
      if (query) return list('', page, query);
      const category = typeof filters.category === 'string' ? filters.category : '';
      const tag = typeof filters.tag === 'string' ? filters.tag : '';
      return list(category ? `/category/${category}` : tag ? `/tag/${tag}` : '', page);
    },
    async getMangaDetails(manga: MangaSummary): Promise<MangaDetails> {
      const { document } = await load(BASE_URL + manga.url);
      const title = document.selectFirst('.post-conteudo h1')?.text().trim();
      if (!title) throw new Error('Manga title is mandatory');
      return {
        url: manga.url,
        title,
        description: document
          .select('.post-texto p')
          .map((p) => p.text().trim())
          .join('\n'),
        genres: document.select('.post-tags a').map((a) => a.text().trim()),
        thumbnailUrl: document.selectFirst('meta[property=og:image]')?.attr('content') || manga.thumbnailUrl,
        // Each post is a single comic, usually completed once uploaded.
        status: 'completed',
      };
    },
    async getChapters(manga: MangaSummary): Promise<Chapter[]> {
      const { document, url } = await load(BASE_URL + manga.url);
      const published = Date.parse(
        document.selectFirst('meta[property=article:published_time]')?.attr('content') ?? '',
      );
      return [
        {
          name: 'Capítulo Único',
          url: relativeUrl(url),
          uploadedAt: Number.isNaN(published) ? undefined : published,
        },
      ];
    },
    async getPages(chapter: Chapter): Promise<Page[]> {
      const { document } = await load(BASE_URL + chapter.url);
      const gallery = document.select('div.dgwt-jg-gallery figure.dgwt-jg-item a');
      if (gallery.length) return gallery.map((a, index) => ({ index, imageUrl: a.absUrl('href') || '' }));
      return document
        .select('.post-texto img')
        .map((img, index) => ({ index, imageUrl: img.absUrl('src') || img.absUrl('data-lazy-src') || '' }));
    },
    imageHeaders: () => headers,
    resolveUrl(url: string): MangaSummary | null {
      const match = /^https?:\/\/([^/?#]+)(\/[^?#]+)/i.exec(url.trim());
      return match && match[1]!.toLowerCase() === hostOf(BASE_URL) ? { url: match[2]!, title: '' } : null;
    },
    getWebUrl: (item) => BASE_URL + item.url,
  }),
});
